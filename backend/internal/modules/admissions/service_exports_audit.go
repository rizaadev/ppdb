package admissions

import (
	"context"
	"fmt"
	"path"
	"strings"
	"time"

	"github.com/google/uuid"
)

const demoExportKeyPrefix = "demo-exports/"

// CreateExportJob schedules (via River in PG mode) or generates (in demo mode) a national export artifact.
func (s *Service) CreateExportJob(
	ctx context.Context,
	tenantID uuid.UUID,
	input CreateExportJobInput,
	actor ActorContext,
) (*ExportJob, error) {
	format := strings.ToLower(strings.TrimSpace(input.Format))
	fields := map[string]string{}
	if input.UnitID == uuid.Nil {
		fields["unit_id"] = "Unit sekolah wajib dipilih."
	}
	if input.PeriodID == uuid.Nil {
		fields["period_id"] = "Periode penerimaan wajib dipilih."
	}
	switch format {
	case ExportFormatDapodikXLSX, ExportFormatEMISXLSX, ExportFormatCustomCSV:
	default:
		fields["format"] = "Format ekspor harus dapodik_xlsx, emis_xlsx, atau custom_csv."
	}
	if len(fields) > 0 {
		return nil, &ValidationError{Message: "Parameter ekspor data tidak valid.", Fields: fields}
	}

	job, err := s.store.CreateExportJob(ctx, tenantID, input.UnitID, input.PeriodID, format, actor)
	if err != nil {
		return nil, err
	}
	s.enrichExportJobDownload(job)
	return job, nil
}

// GetExportJob fetches a single export job and resolves its download URL when completed.
func (s *Service) GetExportJob(ctx context.Context, tenantID, jobID uuid.UUID) (*ExportJob, error) {
	job, err := s.store.GetExportJob(ctx, tenantID, jobID)
	if err != nil {
		return nil, err
	}
	if job == nil {
		return nil, ErrExportJobNotFound
	}
	s.enrichExportJobDownload(job)
	return job, nil
}

// ListExportJobs returns recent export jobs visible to the staff member's RBAC unit scope.
func (s *Service) ListExportJobs(ctx context.Context, tenantID uuid.UUID, allowedUnitIDs []uuid.UUID, limit int) ([]ExportJob, error) {
	if limit <= 0 || limit > 100 {
		limit = 25
	}
	jobs, err := s.store.ListExportJobs(ctx, tenantID, allowedUnitIDs, limit)
	if err != nil {
		return nil, err
	}
	for i := range jobs {
		s.enrichExportJobDownload(&jobs[i])
	}
	return jobs, nil
}

// DownloadExportArtifact resolves either demo generated bytes or a presigned S3 GET redirect URL.
func (s *Service) DownloadExportArtifact(ctx context.Context, tenantID, jobID uuid.UUID) (*DemoExportFile, string, *ExportJob, error) {
	job, err := s.GetExportJob(ctx, tenantID, jobID)
	if err != nil {
		return nil, "", nil, err
	}
	if job.Status != ExportStatusCompleted || job.ResultStorageKey == nil || *job.ResultStorageKey == "" {
		return nil, "", job, ErrExportNotReady
	}
	if strings.HasPrefix(*job.ResultStorageKey, demoExportKeyPrefix) {
		file, err := s.store.GetDemoExportFile(ctx, tenantID, jobID)
		if err != nil {
			return nil, "", job, err
		}
		if file == nil {
			return nil, "", job, ErrExportNotReady
		}
		return file, "", job, nil
	}
	if s.presigner != nil {
		presigned, err := s.presigner.PresignGetObject(*job.ResultStorageKey, 15*time.Minute)
		if err == nil && presigned.URL != "" {
			return nil, presigned.URL, job, nil
		}
	}
	return nil, "", job, ErrExportNotReady
}

// ListTenantAuditLogs queries tenant-wide or application-filtered immutable audit logs.
func (s *Service) ListTenantAuditLogs(ctx context.Context, tenantID uuid.UUID, filter TenantAuditLogFilter) ([]TenantAuditLogItem, error) {
	if filter.Limit <= 0 || filter.Limit > 200 {
		filter.Limit = 100
	}
	if filter.ActionType != nil {
		trimmed := strings.TrimSpace(*filter.ActionType)
		if trimmed == "" {
			filter.ActionType = nil
		} else {
			filter.ActionType = &trimmed
		}
	}
	return s.store.ListTenantAuditLogs(ctx, tenantID, filter)
}

func (s *Service) enrichExportJobDownload(job *ExportJob) {
	if job == nil || job.ResultStorageKey == nil || *job.ResultStorageKey == "" {
		return
	}
	base := path.Base(*job.ResultStorageKey)
	if base != "" && base != "." {
		job.Filename = &base
	}
	if job.Status != ExportStatusCompleted {
		return
	}
	if strings.HasPrefix(*job.ResultStorageKey, demoExportKeyPrefix) {
		url := fmt.Sprintf("/api/v1/admin/exports/%s/download", job.ID.String())
		job.DownloadURL = &url
		return
	}
	if s.presigner != nil {
		presigned, err := s.presigner.PresignGetObject(*job.ResultStorageKey, 15*time.Minute)
		if err == nil && presigned.URL != "" {
			url := presigned.URL
			job.DownloadURL = &url
		}
	}
}

